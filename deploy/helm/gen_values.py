"""
Writes the chart's role values (six-sevens/values-roles.yaml) from Terraform's role table, so the chart can't drift
from what Cloud Run runs. Sources, all in deploy/terraform: roles.json (sizes, secrets, env), migration.json (the
consumers GKE runs) and subscriptions.json (which roles consume events; exported from backend/app/events/types.py).

    python deploy/helm/gen_values.py           # write it
    python deploy/helm/gen_values.py --check   # fail if it's out of date (CI)

The output is JSON, which is valid YAML. Standard library only.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TERRAFORM = HERE.parent / "terraform"
OUT = HERE / "six-sevens" / "values-roles.yaml"

HEADER = "# Generated by deploy/helm/gen_values.py from deploy/terraform/*.json. Don't edit by hand.\n"


def secret_id(name: str) -> str:
    """Secret Manager's id for an environment variable name, as iam.tf names them."""
    return name.lower().replace("_", "-")


def render() -> str:
    table = json.loads((TERRAFORM / "roles.json").read_text())
    pull_roles = set(json.loads((TERRAFORM / "migration.json").read_text())["pull_roles"])
    consumers = set(json.loads((TERRAFORM / "subscriptions.json").read_text()))
    unknown = pull_roles - consumers
    if unknown:
        raise SystemExit(f"migration.json lists {sorted(unknown)}, which consume no events")
    roles = {}
    for name, role in table["roles"].items():
        consumer = name in consumers
        roles[name] = {
            "cpu": role["cpu"],
            "memory": role["memory"],
            "concurrency": role["concurrency"],
            "min": role["gke"]["min"],
            "max": role["max"],
            "drainSeconds": role["gke"]["drain_seconds"],
            "behindGateway": role["public"],
            "consumer": consumer,
            # A consumer runs on GKE only once its subscription is pulled; a non-consumer (api) always runs.
            "enabled": (name in pull_roles) if consumer else True,
            "env": role["env"],
            "secrets": [{"env": s, "id": secret_id(s)} for s in role["secrets"]],
        }
    values = {"commonEnv": table["common_env"], "roles": roles}
    return HEADER + json.dumps(values, indent=2, sort_keys=True) + "\n"


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            raise SystemExit(f"{OUT.name} is out of date: run python deploy/helm/gen_values.py")
        print(f"{OUT.name} is up to date")
        return
    OUT.write_text(text, newline="\n")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
