def _make_custom_pdf(path: Path) -> None:
    doc = pymupdf.open()
    page = doc.new_page(width=400, height=300)
    page.insert_text((72, 100), "Custom Tenant", fontsize=12, fontname="helv")
    page.insert_text((72, 140), "Rent 1500.00", fontsize=12, fontname="helv")
